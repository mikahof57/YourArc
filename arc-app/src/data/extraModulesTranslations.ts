/**
 * Returns a localized ModuleContentItem based on the active language ('en' or 'de').
 */
export function getLocalizedModuleItem(item: ModuleContentItem, lang: string = 'en'): ModuleContentItem {
  if (lang !== 'en') {
    return item;
  }

  const translation = EXTRA_MODULES_EN_TRANSLATIONS[item.id];
  if (!translation) {
    // If not specifically translated, format author subtitle from "Autor:" to "Author:" if present
    const adjustedSubtitle = item.subtitle.startsWith('Autor: ')
      ? item.subtitle.replace('Autor: ', 'Author: ')
      : item.subtitle;

    return {
      ...item,
      subtitle: adjustedSubtitle,
    };
  }

  return {
    id: item.id,
    title: translation.title || item.title,
    subtitle: translation.subtitle || (item.subtitle.startsWith('Autor: ') ? item.subtitle.replace('Autor: ', 'Author: ') : item.subtitle),
    content: translation.content || item.content,
    tags: translation.tags || item.tags,
  };
}
